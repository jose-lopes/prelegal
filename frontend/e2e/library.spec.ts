import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";
import { complete, completed, enter, replyWith, say } from "./chat-fixtures";

test("saves, reopens, updates and downloads private documents across sign-in", async ({ page, browser }) => {
  await enter(page);
  await complete(page);
  await page.getByLabel("Document name").fill("Acme research draft");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Saved to your account" })).toBeVisible();
  await page.getByRole("button", { name: "My documents", exact: true }).click();
  await expect(page.getByRole("button", { name: /Acme research draft.*Open draft/ })).toBeVisible();
  await page.screenshot({ path: "test-results/desktop-library.png", fullPage: true });
  const history = await (await page.request.get("/api/agreements")).json();
  const user = await (await page.request.get("/api/auth/session")).json();
  const other = await browser.newContext();
  const otherResponse = await other.request.post(new URL("/api/auth/signup", page.url()).href, { data: { email: `other-${randomUUID()}@example.com`, password: "a long test password" } });
  expect(otherResponse.ok()).toBe(true);
  const documentsURL = new URL("/api/agreements", page.url()).href;
  expect(await (await other.request.get(documentsURL)).json()).toEqual([]);
  expect((await other.request.get(`${documentsURL}/${history[0].id}`)).status()).toBe(404);
  const original = await (await page.request.get(`/api/agreements/${history[0].id}`)).json();
  expect((await other.request.put(`${documentsURL}/${history[0].id}`, { data: { documentId: "mutual-nda", title: "Stolen", fields: original.fields } })).status()).toBe(404);
  await other.close();
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  await page.getByLabel("Email address").fill(user.email);
  await page.getByLabel("Password", { exact: true }).fill("a long test password");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByRole("button", { name: /Acme research draft.*Open draft/ }).click();
  await expect(page.getByRole("article")).toContainText("Acme & José, Inc.");
  await expect(page.getByLabel("Document name")).toHaveValue("Acme research draft");
  await replyWith(page, { ...completed(), purpose: "A corrected purpose." });
  await say(page, "Change the purpose to a corrected purpose.");
  await page.getByLabel("Document name").fill("Acme revised draft");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Saved to your account" })).toBeVisible();
  expect(await (await page.request.get("/api/agreements")).json()).toHaveLength(1);
  await page.reload();
  await page.getByRole("button", { name: /Acme revised draft.*Open draft/ }).click();
  await expect(page.getByRole("article")).toContainText("A corrected purpose.");
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download PDF" }).click();
  expect(await (await download).failure()).toBeNull();
  await page.getByRole("button", { name: "My documents", exact: true }).click();
  await page.getByRole("button", { name: "+ New agreement", exact: true }).click();
  await page.getByLabel("Document type", { exact: true }).selectOption("mutual-nda");
  await expect(page.getByRole("article")).not.toContainText("Acme & José, Inc.");
  await page.getByLabel("Document name").fill("Second NDA");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Saved to your account" })).toBeVisible();
  expect(await (await page.request.get("/api/agreements")).json()).toHaveLength(2);
  await page.getByRole("button", { name: "My documents", exact: true }).click();
  await page.getByRole("button", { name: /Second NDA.*Open draft/ }).click();
  await expect(page.locator(".primary-button")).toBeDisabled();
});

test("save failure preserves the draft and retries without adding duplicate documents", async ({ page }) => {
  await enter(page);
  await complete(page);
  await page.route("**/api/agreements", route => route.request().method() === "POST" ? route.fulfill({ status: 500, json: { error: "Unable to save your document. Please retry." } }) : route.continue());
  await page.getByRole("button", { name: "Download PDF" }).click();
  await expect(page.getByRole("region", { name: "Save your draft" }).getByRole("alert")).toContainText("Unable to save");
  await expect(page.getByRole("article")).toContainText("Acme & José, Inc.");
  await page.unroute("**/api/agreements");
  await page.getByRole("button", { name: "Retry save" }).click();
  await expect(page.getByRole("status").filter({ hasText: "Saved to your account" })).toBeVisible();
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Saved to your account" })).toBeVisible();
  expect(await (await page.request.get("/api/agreements")).json()).toHaveLength(1);
});

test("library errors can be retried and an expired session returns to sign in", async ({ page }) => {
  await enter(page);
  await page.route("**/api/agreements", route => route.fulfill({ status: 500, json: { error: "Unavailable" } }));
  await page.getByRole("button", { name: "My documents", exact: true }).click();
  await expect(page.locator(".workspace-error")).toContainText("Unable to load");
  await page.unroute("**/api/agreements");
  await page.getByRole("button", { name: "Retry", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your next agreement starts here" })).toBeVisible();
  await page.request.post("/api/auth/signout");
  await page.getByRole("button", { name: "My documents", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Welcome back" })).toBeVisible();
});
